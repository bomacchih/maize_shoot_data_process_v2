has_10x_files <- function(path) {
  matrix_present <- any(file.exists(file.path(
    path, c("matrix.mtx", "matrix.mtx.gz")
  )))
  barcode_present <- any(file.exists(file.path(
    path, c("barcodes.tsv", "barcodes.tsv.gz")
  )))
  feature_present <- any(file.exists(file.path(
    path,
    c("features.tsv", "features.tsv.gz", "genes.tsv", "genes.tsv.gz")
  )))
  matrix_present && barcode_present && feature_present
}

find_10x_matrix_directory <- function(reference_root, run_id) {
  run_root <- file.path(reference_root, run_id)
  if (!dir.exists(run_root)) {
    stop(
      "Raw count directory not found for ", run_id, ": ", run_root,
      "\nPlace the 10x-style matrix under data/raw/scRNA_reference/", run_id,
      "/filtered_feature_bc_matrix/."
    )
  }

  preferred <- c(
    file.path(run_root, "filtered_feature_bc_matrix"),
    file.path(run_root, "raw_feature_bc_matrix"),
    file.path(run_root, "outs", "filtered_feature_bc_matrix"),
    file.path(run_root, "outs", "raw_feature_bc_matrix"),
    run_root
  )
  preferred <- preferred[vapply(preferred, has_10x_files, logical(1))]

  if (length(preferred) == 1L) return(preferred)
  if (length(preferred) > 1L) {
    stop(
      "More than one 10x matrix directory was found for ", run_id, ":\n  ",
      paste(preferred, collapse = "\n  ")
    )
  }

  all_directories <- list.dirs(run_root, recursive = TRUE, full.names = TRUE)
  candidates <- all_directories[
    vapply(all_directories, has_10x_files, logical(1))
  ]
  if (length(candidates) != 1L) {
    stop(
      "Expected exactly one 10x matrix directory for ", run_id,
      "; found ", length(candidates), "."
    )
  }
  candidates
}

read_gene_expression_matrix <- function(matrix_directory) {
  # gene.column = 1 retains stable maize gene identifiers and prevents symbol
  # ambiguity when this reference is later compared with the Visium dataset.
  counts <- Read10X(
    data.dir = matrix_directory,
    gene.column = 1,
    unique.features = TRUE,
    strip.suffix = FALSE
  )

  if (is.list(counts)) {
    preferred_names <- c("Gene Expression", "RNA", "gene_expression")
    selected <- intersect(preferred_names, names(counts))
    if (length(selected) == 0L) {
      stop(
        "Read10X returned multiple assays but no Gene Expression matrix: ",
        paste(names(counts), collapse = ", ")
      )
    }
    counts <- counts[[selected[1L]]]
  }

  if (!inherits(counts, "sparseMatrix")) counts <- as(counts, "dgCMatrix")
  counts
}

detect_doublets_and_retain_singlets <- function(seurat_object, run_id) {
  message("Running scDblFinder for ", run_id)
  sce <- as.SingleCellExperiment(seurat_object, assay = "RNA")

  set.seed(random_seed)
  sce <- scDblFinder(
    sce,
    samples = NULL,
    returnType = "sce",
    verbose = TRUE
  )

  seurat_object$scDblFinder.score <- colData(sce)$scDblFinder.score
  seurat_object$scDblFinder.class <- as.character(
    colData(sce)$scDblFinder.class
  )

  class_counts <- as.data.frame(table(
    SRA_run = run_id,
    scDblFinder_class = seurat_object$scDblFinder.class
  ))
  class_counts$before_filtering <- ncol(seurat_object)

  singlets <- colnames(seurat_object)[
    seurat_object$scDblFinder.class == "singlet"
  ]
  if (length(singlets) == 0L) {
    stop("scDblFinder did not retain any singlets for ", run_id)
  }
  seurat_object <- subset(seurat_object, cells = singlets)
  class_counts$singlets_retained <- ncol(seurat_object)

  rm(sce)
  gc(verbose = FALSE)
  list(object = seurat_object, summary = class_counts)
}

load_and_filter_library <- function(run_id) {
  matrix_directory <- find_10x_matrix_directory(raw_reference_dir, run_id)
  message("Reading ", run_id, " from ", matrix_directory)
  counts <- read_gene_expression_matrix(matrix_directory)

  object <- CreateSeuratObject(
    counts = counts,
    project = run_id,
    assay = "RNA",
    min.cells = min_cells,
    min.features = min_features
  )
  object$SRA_run <- run_id
  object$library_id <- run_id
  object$reference_dataset <- "maize_shoot_scRNA"

  detected <- detect_doublets_and_retain_singlets(object, run_id)
  detected$matrix_directory <- matrix_directory
  detected
}

