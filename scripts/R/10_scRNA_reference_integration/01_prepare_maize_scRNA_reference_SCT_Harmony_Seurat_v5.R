# -----------------------------
# 6. Harmony layer integration
# -----------------------------

set.seed(random_seed)
sc_reference <- IntegrateLayers(
  object = sc_reference,
  method = HarmonyIntegration,
  orig.reduction = "pca",
  new.reduction = "harmony",
  assay = "SCT",
  dims = seq_len(integration_pcs),
  verbose = TRUE
)

if (!"harmony" %in% Reductions(sc_reference)) {
  stop("Harmony integration did not create the 'harmony' reduction.")
}
if (ncol(Embeddings(sc_reference, reduction = "harmony")) < integration_pcs) {
  stop("The Harmony reduction contains fewer than 30 dimensions.")
}

# Rejoin the RNA library layers after integration, as required before later
# differential-expression or reference-comparison analyses. SCTransform creates
# a unified SCT assay; if a future Seurat release retains multiple SCT data
# layers, join those as well.
sc_reference <- JoinLayers(sc_reference, assay = "RNA")
sct_data_layers <- grep(
  "^(counts|data)($|\\.)",
  Layers(sc_reference[["SCT"]]),
  value = TRUE
)
if (length(grep("^data($|\\.)", sct_data_layers)) > 1L ||
    length(grep("^counts($|\\.)", sct_data_layers)) > 1L) {
  sc_reference <- JoinLayers(sc_reference, assay = "SCT")
}

