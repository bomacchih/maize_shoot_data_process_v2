#!/usr/bin/env python3
"""Merge Seurat and Velocyto data and compare stochastic/dynamical velocity.

Expected project structure
--------------------------
data/
├── raw/loom/
│   ├── XGE20_UL01_B73V5S210_short_MTCL.loom
│   ├── XGE20_UL02_B73V5S210_short_MTCL.loom
│   └── ... one loom file for each of the 14 samples
└── processed/RNA_velocity/seurat_export/
    ├── counts.mtx
    ├── features.csv
    ├── spot_metadata.csv
    ├── pca.csv
    └── umap.csv

The loom files must have been generated from the corresponding Space Ranger
outputs with Velocyto and the Zm-B73-REFERENCE-NAM-5.0 GTF. This program does
not run shell commands or Velocyto. It performs the Python/scVelo portion only.

Run scripts/R/08_RNA_velocity/01_export_Seurat_for_scVelo.R first. This program
reconstructs the Seurat data as AnnData, preserves its metadata/PCA/UMAP, joins
spliced and unspliced loom layers by exact spot and gene identifiers, and then
runs scVelo's stochastic and dynamical models on the same preprocessing,
neighborhood graph, moments, and Seurat UMAP. Only SAM, P1_P2, P3, P4, and P5
are retained.

Workflow references:
- Sam Morabito, "RNA velocity analysis with scVelo" (Seurat export/merge).
- scVelo dynamical-model documentation (filtering, moments, dynamics, velocity).
"""

